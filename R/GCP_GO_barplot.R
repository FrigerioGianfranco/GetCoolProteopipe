#' Produce bar plot graphs out of Gene Ontologies (GO) results.
#'
#' It creates bar plot graphs considering the output of the GCP_GO() function.
#'
#' @param GO_list A list obtained with the function GCP_GO().
#' @param barfill A name of a numeric column of the GO result data frames. Ideally one of: "pvalue", "p.adjust", "qvalue"
#' @param minCount numeric. A minimum number of Count to be included in the graph
#' @param maxDescriptions Numeric. Maximum number of bars to plot. rows with the lowest values of the column indicated in barfill and, in case of tie, with the higher number of Count, will be prioritised.
#'
#' @return A list of ggplot objects.
#'
#'
#' @examples
#'
#' \dontrun{
#' this_GO_list <- GCP_GO(GCPlist = GCPlist12a2,
#'                        name_column_groups = "Group_multi",
#'                        OrgDb = "mouse")
#'
#' GO_bar_plots <- GCP_GO_barplot(GO_list = this_GO_list,
#'                                barfill = "pvalue")
#'
#' export_figures(GO_bar_plots)
#'
#' }
#'
#'
#' @export
GCP_GO_barplot <- function(GO_list,
                           barfill = "pvalue",
                           minCount = 1,
                           maxDescriptions = Inf) {

  if (!is.list(GO_list)) {stop("GO_list must be a list generated by GCP_GO()")}
  if (is.null(names(GO_list))) {stop("GO_list must be a list generated by GCP_GO()")}
  if (any(duplicated(names(GO_list)))) {stop("GO_list must be a list generated by GCP_GO()")}
  if (!"GO_results" %in% names(GO_list)) {stop("GO_list must be a list generated by GCP_GO()")}

  if (!is.list(GO_list$GO_results)) {stop("GO_list$GO_results must be a list")}
  if (length(GO_list$GO_results) < 1) {stop("GO_list$GO_results must be a non-empty list")}
  if (!all(unname(map_lgl(GO_list$GO_results, is.null)) | unname(map_lgl(GO_list$GO_results, is.data.frame)))) {stop("GO_list$GO_results must be a list of NULL or of data frames")}
  if (is.null(names(GO_list$GO_results))) {stop("GO_list$GO_results must have names")}
  if (any(is.na(names(GO_list$GO_results))))  {stop("GO_list$GO_results must have names")}
  if (any(duplicated(names(GO_list$GO_results)))) {stop("GO_list$GO_results must not contain duplicated names")}
  if (!all(map_lgl(names(GO_list$GO_results), nzchar)))  {stop("GO_list$GO_results must not have empty names")}

  if (all(unname(map_lgl(GO_list$GO_results, is.null)))) {
    cat("\n\nNo GO results at all!! No bar plot has been created!\n\n")
    thebarplotlist <- list()
  } else {

    if (length(minCount)!=1) {stop("minCount must be of length 1")}
    if (is.na(minCount)) {stop("minCount must not be NA")}
    if (!is.numeric(minCount)) {stop("minCount must be a number")}
    if (is.infinite(minCount)) {stop("minCount must not be infinite")}
    if (as.integer(minCount) != minCount) {stop("minCount must be an integer number")}
    if (minCount<0) {stop("minCount must not be negative")}

    if (length(maxDescriptions)!=1) {stop("maxDescriptions must be of length 1")}
    if (is.na(maxDescriptions)) {stop("maxDescriptions must not be NA")}
    if (!is.numeric(maxDescriptions)) {stop("maxDescriptions must be a number")}
    if (!is.infinite(maxDescriptions)) {
      if (as.integer(maxDescriptions) != maxDescriptions) {stop("maxDescriptions must be an integer number, or infinite")}
    }
    if (maxDescriptions<=0) {stop("maxDescriptions must not be zero or negative")}

    if (length(barfill)!=1) {stop("barfill must be of length 1")}
    if (is.na(barfill)) {stop("barfill must not be NA")}
    if (!is.character(barfill))  {stop("barfill must be a character")}
    if (!nzchar(barfill)) {stop("barfill must not be an empty string")}
    if (barfill %in% c("ONTOLOGY", "Description", "Count")) {stop('barfill must not be "ONTOLOGY", "Description", or "Count"')}

    col_names_that_must_be_present <- c("ONTOLOGY", "Description", "Count", barfill)
    where_those_are_absent <- rep(list(character()), length(col_names_that_must_be_present))
    names(where_those_are_absent) <- col_names_that_must_be_present
    where_those_are_not_suitable <- rep(list(character()), length(col_names_that_must_be_present))
    names(where_those_are_not_suitable) <- col_names_that_must_be_present
    where_those_are_NA <- rep(list(character()), length(col_names_that_must_be_present))
    names(where_those_are_NA) <- col_names_that_must_be_present

    for (GOvalid in names(GO_list$GO_results)[which(!unname(map_lgl(GO_list$GO_results, is.null)))]) {
      for (cntmbp in col_names_that_must_be_present) {
        if (!cntmbp %in% colnames(GO_list$GO_results[[GOvalid]])) {
          where_those_are_absent[[cntmbp]] <- c(where_those_are_absent[[cntmbp]], GOvalid)
        } else {
          if (cntmbp %in% c("Count", barfill)) {
            if (!is.numeric(pull(GO_list$GO_results[[GOvalid]], cntmbp))) {
              where_those_are_not_suitable[[cntmbp]] <- c(where_those_are_not_suitable[[cntmbp]], GOvalid)
            } else if (!all(unname(map_lgl(pull(GO_list$GO_results[[GOvalid]], cntmbp), is.finite)))) {
              where_those_are_NA[[cntmbp]] <- c(where_those_are_NA[[cntmbp]], GOvalid)
            }
          }
          if (cntmbp == "Description" & "ONTOLOGY" %in% colnames(GO_list$GO_results[[GOvalid]])) {
            for (oont in unique(GO_list$GO_results[[GOvalid]]$ONTOLOGY)) {
              this_df_to_checkk <- filter(GO_list$GO_results[[GOvalid]], ONTOLOGY == oont)
              if (any(duplicated(pull(this_df_to_checkk, cntmbp)))) {
                where_those_are_not_suitable[[cntmbp]] <- c(where_those_are_not_suitable[[cntmbp]], paste0(GOvalid, "_", oont))
              }
            }
          }

          if (any(is.na(pull(GO_list$GO_results[[GOvalid]], cntmbp)))) {
            where_those_are_NA[[cntmbp]] <- c(where_those_are_NA[[cntmbp]], GOvalid)
          }
        }
      }
    }

    if (any(unname(map_lgl(where_those_are_absent, \(x) length(x)>0))) | any(unname(map_lgl(where_those_are_not_suitable, \(x) length(x)>0))) | any(unname(map_lgl(where_those_are_NA, \(x) length(x)>0)))) {
      msg_to_print <- "Data frame of GO results not suitable because:\n"
      if (any(unname(map_lgl(where_those_are_absent, \(x) length(x)>0)))) {
        for (missingname in names(where_those_are_absent)[which(unname(map_lgl(where_those_are_absent, \(x) length(x)>0)))]) {
          new_msg_to_print <- paste0("'", missingname, "' is absent as column name in '", paste0(where_those_are_absent[[missingname]], collapse = "', '"), "'\n" )
          msg_to_print <- paste0(msg_to_print, new_msg_to_print)
        }
      }
      if (any(unname(map_lgl(where_those_are_not_suitable, \(x) length(x)>0)))) {
        for (notsuitable in names(where_those_are_not_suitable)[which(unname(map_lgl(where_those_are_not_suitable, \(x) length(x)>0)))]) {
          if (notsuitable  %in% c("Count", barfill)) {
            new_msg_to_print <- paste0("'", notsuitable, "' contains non-numeric data in '", paste0(where_those_are_not_suitable[[notsuitable]], collapse = "', '"), "'\n" )
            msg_to_print <- paste0(msg_to_print, new_msg_to_print)
          }
          if (notsuitable == "Description") {
            new_msg_to_print <- paste0("'", notsuitable, "' contains duplicated in '", paste0(where_those_are_not_suitable[[notsuitable]], collapse = "', '"), "'\n" )
            msg_to_print <- paste0(msg_to_print, new_msg_to_print)
          }
        }
      }
      if (any(unname(map_lgl(where_those_are_NA, \(x) length(x)>0)))) {
        for (colwithNA in names(where_those_are_NA)[which(unname(map_lgl(where_those_are_NA, \(x) length(x)>0)))]) {
          new_msg_to_print <- paste0("'", colwithNA, "' contains missing values or infinite values in '", paste0(unique(where_those_are_NA[[colwithNA]]), collapse = "', '"), "'\n" )
          msg_to_print <- paste0(msg_to_print, new_msg_to_print)
        }
      }


      stop(msg_to_print)
    }



    thebarplotlist <- list()
    onts <- c("BP", "MF", "CC")
    cat("\n")

    for (GOr in names(GO_list$GO_results)) {
      if (is.null(GO_list$GO_results[[GOr]])) {
        cat(paste0("\n", GOr, ":\n  no results!\n"))
      } else {
        cat(paste0("\n", GOr, ":\n"))
        this_GO_results <- GO_list$GO_results[[GOr]]

        for (tont in onts) {
          if (!tont%in%this_GO_results$ONTOLOGY) {
            cat(paste0("  ", tont,": no results!\n"))
          } else {
            this_GO_results_this_tont <- filter(this_GO_results, ONTOLOGY == tont)
            this_GO_results_this_tont_minCount <- filter(this_GO_results_this_tont, Count>=minCount)

            if (nrow(this_GO_results_this_tont_minCount)<1) {
              cat(paste0("  ", tont,": no results after applying minCount (set at ", minCount,")!\n"))
            } else {

              if (is.infinite(maxDescriptions)) {
                this_GO_results_this_tont_minCount_maxDescr <- this_GO_results_this_tont_minCount
              } else {
                this_GO_results_this_tont_minCount_arranged <-  arrange(this_GO_results_this_tont_minCount, !!sym(barfill), desc(Count))
                if (maxDescriptions<nrow(this_GO_results_this_tont_minCount_arranged)) {
                  this_GO_results_this_tont_minCount_maxDescr <- this_GO_results_this_tont_minCount_arranged[seq(maxDescriptions), ]
                } else {
                  this_GO_results_this_tont_minCount_maxDescr <- this_GO_results_this_tont_minCount_arranged
                }
              }

              this_barplot_name <- paste0(GOr, "_", tont)

              this_barplot_name_title <- paste0(ifelse(tont=="BP", "Biological process",
                                                       ifelse(tont=="MF", "Molecular function",
                                                              ifelse(tont=="CC", "Cellular component", ""))),
                                                " - ", str_replace_all(GOr, "_", " "))

              cat(paste0("  ", tont,": barplot built with ", nrow(this_GO_results_this_tont_minCount_maxDescr), " rows.\n"))

              this_GO_results_this_tont_minCount_maxDescr_arr <- arrange(this_GO_results_this_tont_minCount_maxDescr, !!sym(barfill), desc(Count))

              this_barplot <- ggplot(data = this_GO_results_this_tont_minCount_maxDescr_arr, mapping = aes(x = reorder(Description, -seq_along(Description)), y = Count, fill = !!sym(barfill))) +
                geom_col() +
                coord_flip() +
                scale_fill_gradient(low = "red",
                                    high = "blue",
                                    name = barfill) +
                labs(title = this_barplot_name_title, x = NULL, y = "Count") +
                theme_bw() +
                theme(plot.title = element_text(face = "bold"),
                      axis.text.y = element_text(color = "black"),
                      panel.grid.major.y = element_blank())


              thebarplotlist[[this_barplot_name]] <- this_barplot
            }
          }
        }
      }
    }
  }

  cat("\n")

  return(thebarplotlist)
}
