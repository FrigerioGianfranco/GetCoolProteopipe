#' Produce dot plot graphs out of Gene Ontologies (GO) results.
#'
#' It creates dot plot graphs considering the output of the GCP_GO() function.
#'
#' @param GO_list A list obtained with the function GCP_GO().
#' @param dotcol A name of a numeric column of the GO result data frames. Ideally one of: "pvalue", "p.adjust", "qvalue".
#' @param xaxis A name of a column of the GO result data frames, such as "GeneRatio" or "BgRatio".
#' @param differential_together logical. If TRUE, and if the results allow it, the differential analyses of the same comparison will be considered togheter in the same graph.
#' @param minCount numeric. A minimum number of Count to be included in the graph.
#' @param maxDescriptions Numeric. Maximum number of lines to plot. rows with the lowest values of the column indicated in dotcol and, in case of tie, with the higher number of Count, will be prioritised.
#'
#' @return A list of ggplot objects.
#'
#'
#' @examples
#'
#' \dontrun{
#' this_GO_list <- GCP_GO(GCPlist = GCPlist12a2,
#'                        name_column_groups = "Group_multi",
#'                        OrgDb = "mouse")
#'
#' GO_dot_plots <- GCP_GO_dotplot(GO_list = this_GO_list,
#'                                dotcol = "pvalue",
#'                                xaxis = "GeneRatio",
#'                                differential_together = TRUE)
#'
#' export_figures(GO_dot_plots)
#'
#' }
#'
#'
#' @export
GCP_GO_dotplot <- function(GO_list,
                           dotcol = "pvalue",
                           xaxis = "GeneRatio",
                           differential_together = TRUE,
                           minCount = 1,
                           maxDescriptions = Inf) {


  if (!is.list(GO_list)) {stop("GO_list must be a list generated by GCP_GO()")}
  if (is.null(names(GO_list))) {stop("GO_list must be a list generated by GCP_GO()")}
  if (any(duplicated(names(GO_list)))) {stop("GO_list must be a list generated by GCP_GO()")}
  if (!"GO_results" %in% names(GO_list)) {stop("GO_list must be a list generated by GCP_GO()")}

  if (!is.list(GO_list$GO_results)) {stop("GO_list$GO_results must be a list")}
  if (length(GO_list$GO_results) < 1) {stop("GO_list$GO_results must be a non-empty list")}
  if (!all(unname(map_lgl(GO_list$GO_results, is.null)) | unname(map_lgl(GO_list$GO_results, is.data.frame)))) {stop("GO_list$GO_results must be a list of NULL or of data frames")}
  if (is.null(names(GO_list$GO_results))) {stop("GO_list$GO_results must have names")}
  if (any(is.na(names(GO_list$GO_results)))) {stop("GO_list$GO_results must have names")}
  if (any(duplicated(names(GO_list$GO_results)))) {stop("GO_list$GO_results must not contain duplicated names")}
  if (!all(map_lgl(names(GO_list$GO_results), nzchar))) {stop("GO_list$GO_results must not have empty names")}

  if (all(unname(map_lgl(GO_list$GO_results, is.null)))) {
    cat("\n\nNo GO results at all!! No plots has been created!\n\n")
    thedotplotlist <- list()
  } else {

    if (length(minCount)!=1) {stop("minCount must be of length 1")}
    if (is.na(minCount)) {stop("minCount must not be NA")}
    if (!is.numeric(minCount)) {stop("minCount must be a number")}
    if (is.infinite(minCount)) {stop("minCount must not be infinite")}
    if (minCount != floor(minCount)) {stop("minCount must be an integer number")}
    if (minCount<0) {stop("minCount must not be negative")}

    if (length(maxDescriptions)!=1) {stop("maxDescriptions must be of length 1")}
    if (is.na(maxDescriptions)) {stop("maxDescriptions must not be NA")}
    if (!is.numeric(maxDescriptions)) {stop("maxDescriptions must be a number")}
    if (!is.infinite(maxDescriptions)) {
      if (maxDescriptions != floor(maxDescriptions)) {stop("maxDescriptions must be an integer number, or infinite")}
    }
    if (maxDescriptions<=0) {stop("maxDescriptions must not be zero or negative")}

    if (length(differential_together)!=1) {stop("differential_together must be exclusively TRUE or FALSE")}
    if (!is.logical(differential_together)) {stop("differential_together must be exclusively TRUE or FALSE")}
    if (is.na(differential_together)) {stop("differential_together must be exclusively TRUE or FALSE")}

    if (length(dotcol)!=1) {stop("dotcol must be of length 1")}
    if (is.na(dotcol)) {stop("dotcol must not be NA")}
    if (!is.character(dotcol)) {stop("dotcol must be a character")}
    if (!nzchar(dotcol)) {stop("dotcol must not be an empty string")}

    if (length(xaxis)!=1) {stop("xaxis must be of length 1")}
    if (is.na(xaxis)) {stop("xaxis must not be NA")}
    if (!is.character(xaxis))  {stop("xaxis must be a character")}
    if (!nzchar(xaxis)) {stop("xaxis must not be an empty string")}

    if (dotcol %in% c("ONTOLOGY", "Description", "Count", "higerlower", xaxis)) {stop('dotcol must not be "ONTOLOGY", "Description", "Count", "higerlower", or the same as xaxis')}
    if (xaxis %in% c("ONTOLOGY", "Description", "Count", "higerlower", dotcol)) {stop('xaxis must not be "ONTOLOGY", "Description", "Count", "higerlower", or the same as dotcol')}


    col_names_that_must_be_present <- c("ONTOLOGY", "Description", "Count", dotcol, xaxis)
    where_those_are_absent <- rep(list(character()), length(col_names_that_must_be_present))
    names(where_those_are_absent) <- col_names_that_must_be_present
    where_those_are_not_suitable <- rep(list(character()), length(col_names_that_must_be_present))
    names(where_those_are_not_suitable) <- col_names_that_must_be_present
    where_those_are_NA <- rep(list(character()), length(col_names_that_must_be_present))
    names(where_those_are_NA) <- col_names_that_must_be_present

    for (GOvalid in names(GO_list$GO_results)[which(!unname(map_lgl(GO_list$GO_results, is.null)))]) {
      for (cntmbp in col_names_that_must_be_present) {
        if (!cntmbp %in% colnames(GO_list$GO_results[[GOvalid]])) {
          where_those_are_absent[[cntmbp]] <- c(where_those_are_absent[[cntmbp]], GOvalid)
        } else {
          if (cntmbp == xaxis) {
            if (!is.numeric(pull(GO_list$GO_results[[GOvalid]], xaxis))) {
              if (any(is.na(pull(GO_list$GO_results[[GOvalid]], xaxis))) || !all(grepl("^[^/]+/[^/]+$", as.character(pull(GO_list$GO_results[[GOvalid]], xaxis))))) {
                where_those_are_not_suitable[[cntmbp]] <- c(where_those_are_not_suitable[[cntmbp]], GOvalid)

              } else {
                GO_list$GO_results[[GOvalid]][, xaxis] <- map_dbl(as.character(pull(GO_list$GO_results[[GOvalid]], xaxis)),
                                                                  function(ratio) {
                                                                    parts <- strsplit(ratio, "/", fixed = TRUE)[[1]]
                                                                    as.numeric(parts[1]) / as.numeric(parts[2])
                                                                  })

                if (!all(unname(map_lgl(pull(GO_list$GO_results[[GOvalid]], xaxis), is.finite)))) {
                  where_those_are_NA[[cntmbp]] <- c(where_those_are_NA[[cntmbp]], GOvalid)
                }
              }
            }
          }
          if (cntmbp %in% c("Count", dotcol, xaxis)) {
            if (!is.numeric(pull(GO_list$GO_results[[GOvalid]], cntmbp))) {
              where_those_are_not_suitable[[cntmbp]] <- c(where_those_are_not_suitable[[cntmbp]], GOvalid)
            } else if (!all(unname(map_lgl(pull(GO_list$GO_results[[GOvalid]], cntmbp), is.finite)))) {
              where_those_are_NA[[cntmbp]] <- c(where_those_are_NA[[cntmbp]], GOvalid)
            }
          }
          if (cntmbp == "Description" & "ONTOLOGY" %in% colnames(GO_list$GO_results[[GOvalid]])) {
            for (oont in unique(GO_list$GO_results[[GOvalid]]$ONTOLOGY)) {
              this_df_to_checkk <- filter(GO_list$GO_results[[GOvalid]], ONTOLOGY == oont)
              if (any(duplicated(pull(this_df_to_checkk, cntmbp)))) {
                where_those_are_not_suitable[[cntmbp]] <- c(where_those_are_not_suitable[[cntmbp]], paste0(GOvalid, "_", oont))
              }
            }
          }

          if (any(is.na(pull(GO_list$GO_results[[GOvalid]], cntmbp)))) {
            where_those_are_NA[[cntmbp]] <- c(where_those_are_NA[[cntmbp]], GOvalid)
          }
        }
      }
    }

    if (any(unname(map_lgl(where_those_are_absent, \(x) length(x)>0))) | any(unname(map_lgl(where_those_are_not_suitable, \(x) length(x)>0))) | any(unname(map_lgl(where_those_are_NA, \(x) length(x)>0)))) {
      msg_to_print <- "Data frame of GO results not suitable because:\n"
      if (any(unname(map_lgl(where_those_are_absent, \(x) length(x)>0)))) {
        for (missingname in names(where_those_are_absent)[which(unname(map_lgl(where_those_are_absent, \(x) length(x)>0)))]) {
          new_msg_to_print <- paste0("'", missingname, "' is absent as column name in '", paste0(where_those_are_absent[[missingname]], collapse = "', '"), "'\n" )
          msg_to_print <- paste0(msg_to_print, new_msg_to_print)
        }
      }
      if (any(unname(map_lgl(where_those_are_not_suitable, \(x) length(x)>0)))) {
        for (notsuitable in names(where_those_are_not_suitable)[which(unname(map_lgl(where_those_are_not_suitable, \(x) length(x)>0)))]) {
          if (notsuitable  %in% c("Count", dotcol, xaxis)) {
            new_msg_to_print <- paste0("'", notsuitable, "' contains not suitable data in '", paste0(where_those_are_not_suitable[[notsuitable]], collapse = "', '"), "'\n" )
            msg_to_print <- paste0(msg_to_print, new_msg_to_print)
          }
          if (notsuitable == "Description") {
            new_msg_to_print <- paste0("'", notsuitable, "' contains duplicated in '", paste0(where_those_are_not_suitable[[notsuitable]], collapse = "', '"), "'\n" )
            msg_to_print <- paste0(msg_to_print, new_msg_to_print)
          }
        }
      }
      if (any(unname(map_lgl(where_those_are_NA, \(x) length(x)>0)))) {
        for (colwithNA in names(where_those_are_NA)[which(unname(map_lgl(where_those_are_NA, \(x) length(x)>0)))]) {
          new_msg_to_print <- paste0("'", colwithNA, "' contains missing values or infinite values in '", paste0(unique(where_those_are_NA[[colwithNA]]), collapse = "', '"), "'\n" )
          msg_to_print <- paste0(msg_to_print, new_msg_to_print)
        }
      }


      stop(msg_to_print)
    }



    if (differential_together) {
      cat("\n\n")

      if (!all(startsWith(names(GO_list$GO_results), "higher_in_") | startsWith(names(GO_list$GO_results), "lower_in_"))) {
        cat('differential_together not done because not all the names of the list GO_list$GO_results start with "higher_in_" or "lower_in_"')
        do_differential_together <- FALSE
      } else {

        name_index_hihger <- which(startsWith(names(GO_list$GO_results), "higher_in_"))
        name_index_lower <- which(startsWith(names(GO_list$GO_results), "lower_in_"))

        name_cleaned_from_hihger <- sub("^higher_in_", "", names(GO_list$GO_results)[name_index_hihger])
        name_cleaned_from_lower <- sub("^lower_in_", "", names(GO_list$GO_results)[name_index_lower])

        if (any(!nzchar(name_cleaned_from_hihger)) | any(!nzchar(name_cleaned_from_lower))) {
          cat("differential togheter not done because there are some comparisons in GO_list$GO_results resulted in empty names")
          do_differential_together <- FALSE
        } else if (any(duplicated(name_cleaned_from_hihger)) | any(duplicated(name_cleaned_from_lower))) {
          cat("differential togheter not done because there are some duplicated in the comparisons in GO_list$GO_results")
          do_differential_together <- FALSE
        } else if (length(name_cleaned_from_hihger)!=length(name_cleaned_from_lower)) {
          cat('differential_together not done because the "higher_in_" and "lower_in_" in GO_list$GO_results do not have the same number')
          do_differential_together <- FALSE
        } else if (!all(all(name_cleaned_from_hihger %in% name_cleaned_from_lower) & all(name_cleaned_from_lower %in% name_cleaned_from_hihger))) {
          cat('differential_together not done because there is not a suitable correspndence between "higher_in_" and "lower_in_" in GO_list$GO_results')
          do_differential_together <- FALSE
        } else {

          matching_higher_lower <- tibble (comparison = name_cleaned_from_hihger,
                                           related_name_index_higher = rep(NA_integer_, length(name_cleaned_from_hihger)),
                                           related_name_index_lower = rep(NA_integer_, length(name_cleaned_from_hihger)))

          all_names_to_consider_for_higher <- names(GO_list$GO_results)
          all_names_to_consider_for_higher[name_index_lower] <- rep("", length(name_index_lower))
          all_names_to_consider_for_higher[name_index_hihger] <- sub("^higher_in_", "", all_names_to_consider_for_higher[name_index_hihger])

          all_names_to_consider_for_lower <- names(GO_list$GO_results)
          all_names_to_consider_for_lower[name_index_hihger] <- rep("", length(name_index_hihger))
          all_names_to_consider_for_lower[name_index_lower] <- sub("^lower_in_", "", all_names_to_consider_for_lower[name_index_lower])


          for (mhli in seq(nrow(matching_higher_lower))) {
            matching_higher_lower$related_name_index_higher[mhli] <- which(all_names_to_consider_for_higher == matching_higher_lower$comparison[mhli])
            matching_higher_lower$related_name_index_lower[mhli] <- which(all_names_to_consider_for_lower == matching_higher_lower$comparison[mhli])
          }

          if (any(is.na(matching_higher_lower$related_name_index_higher)) | any(is.na(matching_higher_lower$related_name_index_lower))) {
            cat('differential_together not done because there is not a suitable correspndence between "higher_in_" and "lower_in_" in GO_list$GO_results')
            do_differential_together <- FALSE
          } else {

            cat("differential_together will be done!")
            do_differential_together <- TRUE

          }
        }
      }
      cat("\n\n")
    } else {
      do_differential_together <- FALSE
    }


    thedotplotlist <- list()
    onts <- c("BP", "MF", "CC")

    if (!do_differential_together) {
      for (GOr in names(GO_list$GO_results)) {
        if (is.null(GO_list$GO_results[[GOr]])) {
          cat(paste0("\n", GOr, ":\n  no results!\n"))
        } else {
          cat(paste0("\n", GOr, ":\n"))
          this_GO_results <- GO_list$GO_results[[GOr]]

          for (tont in onts) {
            if (!tont%in%this_GO_results$ONTOLOGY) {
              cat(paste0("  ", tont,": no results!\n"))
            } else {
              this_GO_results_this_tont <- filter(this_GO_results, ONTOLOGY == tont)
              this_GO_results_this_tont_minCount <- filter(this_GO_results_this_tont, Count>=minCount)

              if (nrow(this_GO_results_this_tont_minCount)<1) {
                cat(paste0("  ", tont,": no results after applying minCount (set at ", minCount,")!\n"))
              } else {

                if (is.infinite(maxDescriptions)) {
                  this_GO_results_this_tont_minCount_maxDescr <- this_GO_results_this_tont_minCount
                } else {
                  this_GO_results_this_tont_minCount_arranged <-  arrange(this_GO_results_this_tont_minCount, !!sym(dotcol), desc(Count))
                  if (maxDescriptions<nrow(this_GO_results_this_tont_minCount_arranged)) {
                    this_GO_results_this_tont_minCount_maxDescr <- this_GO_results_this_tont_minCount_arranged[seq(maxDescriptions), ]
                  } else {
                    this_GO_results_this_tont_minCount_maxDescr <- this_GO_results_this_tont_minCount_arranged
                  }
                }

                this_dotplot_name <- paste0(GOr, "_", tont)

                this_dotplot_name_title <- paste0(ifelse(tont=="BP", "Biological process",
                                                         ifelse(tont=="MF", "Molecular function",
                                                                ifelse(tont=="CC", "Cellular component", ""))),
                                                  " - ", str_replace_all(GOr, "_", " "))

                cat(paste0("  ", tont,": dotplot built with ", nrow(this_GO_results_this_tont_minCount_maxDescr), " rows.\n"))

                this_GO_results_this_tont_minCount_maxDescr_arr <- arrange(this_GO_results_this_tont_minCount_maxDescr, !!sym(xaxis), !!sym(dotcol), desc(Count))

                count_range <- range(this_GO_results_this_tont_minCount_maxDescr_arr$Count)

                if (count_range[1] == count_range[2]) {
                  count_breaks <- count_range[1]
                } else {
                  count_breaks <- pretty(count_range, n = 5)

                  count_breaks <- count_breaks[count_breaks == floor(count_breaks) & count_breaks >= count_range[1] & count_breaks <= count_range[2]]
                }

                this_dotplot <- ggplot(data = this_GO_results_this_tont_minCount_maxDescr_arr, mapping = aes(x = !!sym(xaxis), y = reorder(Description, !!sym(xaxis)))) +
                  geom_point(aes(size = Count, colour = !!sym(dotcol))) +
                  scale_size_continuous(range = c(2, 8), breaks = count_breaks,  labels = as.character(count_breaks)) +
                  scale_colour_gradient(low = "red",
                                        high = "blue",
                                        name = dotcol) +
                  labs(title = this_dotplot_name_title, x = xaxis, y = NULL) +
                  theme_bw() +
                  theme(plot.title = element_text(face = "bold"))


                thedotplotlist[[this_dotplot_name]] <- this_dotplot
              }
            }
          }
        }
      }
    } else {

      for (icmparisn in seq(nrow(matching_higher_lower))) {
        cat(paste0("\n", matching_higher_lower$comparison[icmparisn], ":\n"))
        if (is.null(GO_list$GO_results[[names(GO_list$GO_results)[matching_higher_lower$related_name_index_higher[icmparisn]]]]) & is.null(GO_list$GO_results[[names(GO_list$GO_results)[matching_higher_lower$related_name_index_lower[icmparisn]]]])) {
          cat("  no results!\n")
        } else {
          if (is.null(GO_list$GO_results[[names(GO_list$GO_results)[matching_higher_lower$related_name_index_higher[icmparisn]]]])) {

            this_GO_results <- mutate(GO_list$GO_results[[names(GO_list$GO_results)[matching_higher_lower$related_name_index_lower[icmparisn]]]][, col_names_that_must_be_present],
                                      higerlower = factor(rep("lower", nrow(GO_list$GO_results[[names(GO_list$GO_results)[matching_higher_lower$related_name_index_lower[icmparisn]]]])),
                                                          levels = c("higher", "lower")))

          } else if (is.null(GO_list$GO_results[[names(GO_list$GO_results)[matching_higher_lower$related_name_index_lower[icmparisn]]]])) {
            this_GO_results <- mutate(GO_list$GO_results[[names(GO_list$GO_results)[matching_higher_lower$related_name_index_higher[icmparisn]]]][, col_names_that_must_be_present],
                                      higerlower = factor(rep("higher", nrow(GO_list$GO_results[[names(GO_list$GO_results)[matching_higher_lower$related_name_index_higher[icmparisn]]]])),
                                                          levels = c("higher", "lower")))
          } else {

            this_GO_results <- bind_rows(mutate(GO_list$GO_results[[names(GO_list$GO_results)[matching_higher_lower$related_name_index_higher[icmparisn]]]][, col_names_that_must_be_present],
                                                higerlower = factor(rep("higher", nrow(GO_list$GO_results[[names(GO_list$GO_results)[matching_higher_lower$related_name_index_higher[icmparisn]]]])),
                                                                    levels = c("higher", "lower"))),
                                         mutate(GO_list$GO_results[[names(GO_list$GO_results)[matching_higher_lower$related_name_index_lower[icmparisn]]]][, col_names_that_must_be_present],
                                                higerlower = factor(rep("lower", nrow(GO_list$GO_results[[names(GO_list$GO_results)[matching_higher_lower$related_name_index_lower[icmparisn]]]])),
                                                                    levels = c("higher", "lower"))))
          }

          for (tont in onts) {
            if (!tont%in%this_GO_results$ONTOLOGY) {
              cat(paste0("  ", tont,": no results!\n"))
            } else {
              this_GO_results_this_tont <- filter(this_GO_results, ONTOLOGY == tont)
              this_GO_results_this_tont_minCount <- filter(this_GO_results_this_tont, Count>=minCount)

              if (nrow(this_GO_results_this_tont_minCount)<1) {
                cat(paste0("  ", tont,": no results after applying minCount (set at ", minCount,")!\n"))
              } else {

                if (is.infinite(maxDescriptions)) {
                  this_GO_results_this_tont_minCount_maxDescr <- this_GO_results_this_tont_minCount
                } else {
                  this_GO_results_this_tont_minCount_arranged <-  arrange(this_GO_results_this_tont_minCount, !!sym(dotcol), desc(Count))
                  if (maxDescriptions<nrow(this_GO_results_this_tont_minCount_arranged)) {
                    this_GO_results_this_tont_minCount_maxDescr <- this_GO_results_this_tont_minCount_arranged[seq(maxDescriptions), ]
                  } else {
                    this_GO_results_this_tont_minCount_maxDescr <- this_GO_results_this_tont_minCount_arranged
                  }
                }

                this_dotplot_name <- paste0(matching_higher_lower$comparison[icmparisn], "_", tont)

                this_dotplot_name_title <- paste0(ifelse(tont=="BP", "Biological process",
                                                         ifelse(tont=="MF", "Molecular function",
                                                                ifelse(tont=="CC", "Cellular component", ""))),
                                                  " - ", str_replace_all(matching_higher_lower$comparison[icmparisn], "_", " "))

                cat(paste0("  ", tont,": dotplot built with ", nrow(filter(this_GO_results_this_tont_minCount_maxDescr, higerlower=="higher")), " rows 'hihger' and ", nrow(filter(this_GO_results_this_tont_minCount_maxDescr, higerlower=="lower"))," rows 'lower'.\n"))

                this_GO_results_this_tont_minCount_maxDescr_arr <- arrange(this_GO_results_this_tont_minCount_maxDescr, !!sym(xaxis), !!sym(dotcol), desc(Count))

                count_range <- range(this_GO_results_this_tont_minCount_maxDescr_arr$Count)

                if (count_range[1] == count_range[2]) {
                  count_breaks <- count_range[1]
                } else {
                  count_breaks <- pretty(count_range, n = 5)

                  count_breaks <- count_breaks[count_breaks == floor(count_breaks) & count_breaks >= count_range[1] & count_breaks <= count_range[2]]
                }

                this_dotplot <- ggplot(data = this_GO_results_this_tont_minCount_maxDescr_arr, mapping = aes(x = !!sym(xaxis), y = reorder(Description, !!sym(xaxis)))) +
                  geom_point(aes(size = Count, colour = !!sym(dotcol))) +
                  scale_size_continuous(range = c(2, 8), breaks = count_breaks,  labels = as.character(count_breaks)) +
                  scale_colour_gradient(low = "red",
                                        high = "blue",
                                        name = dotcol) +
                  facet_wrap(~ higerlower, nrow = 1, drop = FALSE) +
                  labs(title = this_dotplot_name_title, x = xaxis, y = NULL) +
                  theme_bw() +
                  theme(plot.title = element_text(face = "bold"))


                thedotplotlist[[this_dotplot_name]] <- this_dotplot
              }
            }
          }
        }
      }
    }
  }

  cat("\n")

  return(thedotplotlist)
}
